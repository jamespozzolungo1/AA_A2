using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using MySqlConnector;

namespace AIStudyPlannerApp.Backend
{
    // stores one timetable entry returned from or saved to the db
    public sealed class TimetableRecord
    {
        public int TimetableItemId { get; set; }
        public int UserId { get; set; }
        public string CourseName { get; set; } = string.Empty;
        // monday = 1 .. sunday = 7
        public int DayOfWeek { get; set; }
        public TimeSpan StartTime { get; set; }
        public TimeSpan EndTime { get; set; }
        public string? Location { get; set; }
        public string? Notes { get; set; }
    }

    // handles timetable operations between the app and the db
    public sealed class TimetableService
    {
        private readonly DatabaseService _database;
        public const int TestUserId = AssignmentService.TestUserId;

        // keeps the db service so this class can create database connections
        public TimetableService(DatabaseService database)
        {
            _database = database;
        }

        // grabs all timetable entries for a user, ordered by weekday and start time
        public async Task<List<TimetableRecord>> GetAllAsync(int userId)
        {
            ValidateUserId(userId);
            var items = new List<TimetableRecord>();

            await using var connection = _database.CreateConnection();
            await connection.OpenAsync();

            // selects this users timetable entries in weekly schedule order
            const string sql = @"
                SELECT TimetableItemId, UserId, CourseName, DayOfWeek,
                       StartTime, EndTime, Location, Notes
                FROM TimetableItems
                WHERE UserId = @UserId
                ORDER BY DayOfWeek, StartTime;";

            await using var command = new MySqlCommand(sql, connection);
            command.Parameters.AddWithValue("@UserId", userId);
            await using var reader = await command.ExecuteReaderAsync();

            while (await reader.ReadAsync())
            {
                items.Add(new TimetableRecord
                {
                    TimetableItemId = reader.GetInt32("TimetableItemId"),
                    UserId = reader.GetInt32("UserId"),
                    CourseName = reader.GetString("CourseName"),
                    DayOfWeek = reader.GetInt32("DayOfWeek"),
                    StartTime = reader.GetTimeSpan("StartTime"),
                    EndTime = reader.GetTimeSpan("EndTime"),
                    Location = reader.IsDBNull(reader.GetOrdinal("Location")) ? null : reader.GetString("Location"),
                    Notes = reader.IsDBNull(reader.GetOrdinal("Notes")) ? null : reader.GetString("Notes")
                });
            }

            return items;
        }

        // adds a timetable entry and returns the ID generated by the db
        public async Task<int> AddAsync(int userId, string courseName, int dayOfWeek,
            TimeSpan startTime, TimeSpan endTime, string? location = null, string? notes = null)
        {
            ValidateUserId(userId);
            ValidateFields(courseName, dayOfWeek, startTime, endTime);

            // inserts the entry and retrieves its newly generated ID
            const string sql = @"
                INSERT INTO TimetableItems
                    (UserId, CourseName, DayOfWeek, StartTime, EndTime, Location, Notes)
                VALUES
                    (@UserId, @CourseName, @DayOfWeek, @StartTime, @EndTime, @Location, @Notes);
                SELECT LAST_INSERT_ID();";

            await using var connection = _database.CreateConnection();
            await connection.OpenAsync();
            await using var command = new MySqlCommand(sql, connection);
            command.Parameters.AddWithValue("@UserId", userId);
            command.Parameters.AddWithValue("@CourseName", courseName.Trim());
            command.Parameters.AddWithValue("@DayOfWeek", dayOfWeek);
            command.Parameters.AddWithValue("@StartTime", startTime);
            command.Parameters.AddWithValue("@EndTime", endTime);
            command.Parameters.AddWithValue("@Location", (object?)location ?? DBNull.Value);
            command.Parameters.AddWithValue("@Notes", (object?)notes ?? DBNull.Value);
            // executes the insert and converts the returned ID to an integer
            return Convert.ToInt32(await command.ExecuteScalarAsync());
        }

        // updates an existing timetable entry belonging to specified user
        public async Task UpdateAsync(int userId, int timetableItemId, string courseName,
            int dayOfWeek, TimeSpan startTime, TimeSpan endTime,
            string? location = null, string? notes = null)
        {
            ValidateUserId(userId);
            if (timetableItemId <= 0) throw new ArgumentOutOfRangeException(nameof(timetableItemId));
            ValidateFields(courseName, dayOfWeek, startTime, endTime);

            const string sql = @"
                UPDATE TimetableItems
                SET CourseName = @CourseName, DayOfWeek = @DayOfWeek,
                    StartTime = @StartTime, EndTime = @EndTime,
                    Location = @Location, Notes = @Notes
                WHERE TimetableItemId = @TimetableItemId AND UserId = @UserId;";

            await using var connection = _database.CreateConnection();
            await connection.OpenAsync();
            await using var command = new MySqlCommand(sql, connection);
            command.Parameters.AddWithValue("@CourseName", courseName.Trim());
            command.Parameters.AddWithValue("@DayOfWeek", dayOfWeek);
            command.Parameters.AddWithValue("@StartTime", startTime);
            command.Parameters.AddWithValue("@EndTime", endTime);
            command.Parameters.AddWithValue("@Location", (object?)location ?? DBNull.Value);
            command.Parameters.AddWithValue("@Notes", (object?)notes ?? DBNull.Value);
            command.Parameters.AddWithValue("@TimetableItemId", timetableItemId);
            command.Parameters.AddWithValue("@UserId", userId);
            await command.ExecuteNonQueryAsync();
        }

        // deletes a timetable entry only when it belongs to specified user
        public async Task DeleteAsync(int userId, int timetableItemId)
        {
            ValidateUserId(userId);
            if (timetableItemId <= 0) throw new ArgumentOutOfRangeException(nameof(timetableItemId));

            const string sql = @"DELETE FROM TimetableItems
                WHERE TimetableItemId = @TimetableItemId AND UserId = @UserId;";

            await using var connection = _database.CreateConnection();
            await connection.OpenAsync();
            await using var command = new MySqlCommand(sql, connection);
            command.Parameters.AddWithValue("@TimetableItemId", timetableItemId);
            command.Parameters.AddWithValue("@UserId", userId);
            await command.ExecuteNonQueryAsync();
        }

        private static void ValidateUserId(int userId)
        {
            if (userId <= 0) throw new ArgumentOutOfRangeException(nameof(userId));
        }

        private static void ValidateFields(string courseName, int dayOfWeek,
            TimeSpan startTime, TimeSpan endTime)
        {
            if (string.IsNullOrWhiteSpace(courseName))
                throw new ArgumentException("Course name is required.", nameof(courseName));

            if (dayOfWeek < 1 || dayOfWeek > 7)
                throw new ArgumentOutOfRangeException(nameof(dayOfWeek), "DayOfWeek must be 1 (Monday) to 7 (Sunday).");

            if (startTime < TimeSpan.Zero || startTime >= TimeSpan.FromDays(1))
                throw new ArgumentOutOfRangeException(nameof(startTime));

            if (endTime <= startTime || endTime >= TimeSpan.FromDays(1))
                throw new ArgumentException("End time must be later than start time.", nameof(endTime));
        }
    }
}